import data from "@/content/specialized-courses.json";
import { units, type Unit } from "@/lib/course";

export type SpecializedCourse = (typeof data.courses)[number] & {
  courseUnits: Unit[];
  lessonCount: number;
};

export const specializedReviewedOn = data.reviewedOn;
export const specializedAvailability = data.appAvailability;

export const specializedCourses: SpecializedCourse[] = data.courses.map(
  (course) => {
    const courseUnits = course.units.map((id) => {
      const unit = units.find((u) => u.id === id);
      if (!unit) throw new Error(`Unknown unit ${id} in course ${course.id}`);
      return unit;
    });
    return {
      ...course,
      courseUnits,
      lessonCount: courseUnits.reduce((n, u) => n + u.lessons.length, 0),
    };
  },
);

export const specializedUnitIDs = new Set(
  data.courses.flatMap((c) => c.units),
);

export const specializedLessonIDs = new Set(
  specializedCourses.flatMap((c) =>
    c.courseUnits.flatMap((u) => u.lessons.map((l) => l.id)),
  ),
);

export const courseURL = (id: string) => `/courses/${encodeURIComponent(id)}`;

export const courseForUnit = (unitID: string) =>
  specializedCourses.find((c) => c.units.includes(unitID));

export const courseForLesson = (lessonID: string) =>
  specializedCourses.find((c) =>
    c.courseUnits.some((u) => u.lessons.some((l) => l.id === lessonID)),
  );

/** Share image generated by app/courses/[id]/opengraph-image.tsx. */
export const courseImageURL = (id: string) => `${courseURL(id)}/opengraph-image`;
